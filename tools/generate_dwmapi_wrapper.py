import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYS_DWMAPI = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32", "dwmapi.dll")


def parse_exports(path):
	data = open(path, "rb").read()
	pe = struct.unpack_from("<I", data, 0x3C)[0]
	opt = pe + 24
	magic = struct.unpack_from("<H", data, opt)[0]
	dd = opt + (112 if magic == 0x20B else 96)
	erva, _esz = struct.unpack_from("<II", data, dd)
	nsec = struct.unpack_from("<H", data, pe + 6)[0]
	secoff = opt + struct.unpack_from("<H", data, pe + 20)[0]
	secs = []
	for i in range(nsec):
		s = data[secoff + i * 40 : secoff + (i + 1) * 40]
		vs, va, rs, ro = struct.unpack_from("<IIII", s, 8)
		secs.append((va, max(vs, rs), ro))

	def r2o(r):
		for va, sz, ro in secs:
			if va <= r < va + sz:
				return ro + (r - va)
		return None

	o = r2o(erva)
	(_chars, _ts, _mj, _mn, _nm, base, nfun, nnam, ea, nnr, eor) = struct.unpack_from("<IIHHIIIIIII", data, o)
	ord_to_name = {}
	for i in range(nnam):
		nrva = struct.unpack_from("<I", data, r2o(nnr) + i * 4)[0]
		no = r2o(nrva)
		j = no
		while data[j] != 0:
			j += 1
		name = data[no:j].decode("latin-1")
		idx = struct.unpack_from("<H", data, r2o(eor) + i * 2)[0]
		ord_to_name[base + idx] = name
	return base, nfun, ord_to_name


def mangle(name):
	"""MASM-safe symbol for an export name."""
	return name if name.isalnum() else "".join(c if c.isalnum() else "_" for c in name)


def main():
	base, nfun, ord_to_name = parse_exports(SYS_DWMAPI)

	asm = [
		"; GENERATED by tools/generate_dwmapi_wrapper.py - do not hand-edit.",
		f"; source: {SYS_DWMAPI} (ordinals {base}..{base + nfun - 1})",
		".code",
	]
	defs = [
		"; GENERATED by tools/generate_dwmapi_wrapper.py - do not hand-edit.",
		"LIBRARY dwmapi",
		"EXPORTS",
	]
	inc = [
		"// GENERATED by tools/generate_dwmapi_wrapper.py - do not hand-edit.",
		'extern "C" {',
	]
	table = ["}", "// { name (nullptr => resolve by ordinal), ordinal, slot }", "static const DwmProxyTarget kDwmProxyTargets[] = {"]

	asm = [
		"; GENERATED by tools/generate_dwmapi_wrapper.py - do not hand-edit.",
		f"; source: {SYS_DWMAPI} (ordinals {base}..{base + nfun - 1})",
		".code",
	]
	for i in range(nfun):
		n = base + i
		name = ord_to_name.get(n)
		sym = mangle(name) if name else f"Ord{n}"
		asm.append(f"PUBLIC Stub_{sym}")
		asm.append(f"PUBLIC g_Target_{sym}")
		n = base + i
		name = ord_to_name.get(n)
		sym = mangle(name) if name else f"Ord{n}"
		asm.append(f"Stub_{sym} PROC")
		asm.append(f"    jmp QWORD PTR [g_Target_{sym}]")
		asm.append(f"Stub_{sym} ENDP")
		inc.append(f'extern "C" void* g_Target_{sym};')
		if name:
			defs.append(f"    {name} = Stub_{sym} @{n}")
			table.append(f'    {{ "{name}", {n}, &g_Target_{sym} }},')
		else:
			defs.append(f"    Stub_{sym} @{n} NONAME")
			table.append(f"    {{ nullptr, {n}, &g_Target_{sym} }},")

	asm.append(".data")
	for i in range(nfun):
		n = base + i
		name = ord_to_name.get(n)
		sym = mangle(name) if name else f"Ord{n}"
		asm.append(f"g_Target_{sym} DQ 0")
	asm.append("END")
	inc.extend(table)
	inc.append("};")

	def emit(rel, lines):
		path = os.path.join(ROOT, rel)
		with open(path, "w", newline="\n") as f:
			f.write("\n".join(lines) + "\n")
		print(f"wrote {rel} ({len(lines)} lines)")

	emit("src/dwmapi_stubs.asm", asm)
	emit("src/dwmapi.def", defs)
	emit("src/dwmapi_targets.inc", inc)
	print(f"{nfun} exports (ordinals {base}..{base + nfun - 1}, {nfun - len(ord_to_name)} NONAME)")


if __name__ == "__main__":
	main()
